--     this plan's own text — found during this task's consumer
--     enumeration and added proactively (Rule 2: a real, disclosed
--     screencopy consumer this host already runs on a keybind).
hl.permission({ binary = "/usr/bin/hyprpicker", type = "screencopy", mode = "allow" })
--   - xdg-desktop-portal-hyprland: the actual running backend binary,
--     confirmed via `pgrep -af xdg-desktop-portal` against the live
